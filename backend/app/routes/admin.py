@admin_bp.route("/add-student", methods=["POST"])
@verify_token
@require_role("admin")
def add_student():
    data = request.json
    email = data.get("email")
    name = data.get("name")
    course = data.get("course") # Display Name
    course_id = data.get("courseId") # Internal ID
    semester = data.get("semester", 1) # Current Semester
    password = data.get("password")
    faculty_assigned = data.get("facultyAssigned", "Not Assigned")

    if not email or not name:
        return jsonify({"error": "Email and Name are required"}), 400

    # Auto-generate password if not provided
    is_auto_generated = False
    if not password:
        is_auto_generated = True
        alphabet = string.ascii_letters + string.digits + "!@#$%&*?"
        password = ''.join(secrets.choice(alphabet) for i in range(12))

    try:
        # 1. Create User in Firebase Auth automatically
        user_record = firebase_auth.create_user(
            email=email,
            display_name=name,
            password=password,
        )
        uid = user_record.uid

        # 2. Create User Role in Firestore (collection: users)
        create_user(uid, {
            "uid": uid,
            "name": name,
            "email": email,
            "role": "student",
            "courseId": course_id,
            "semester": int(semester)
        })

        # 3. Create Student Profile in Firestore (collection: students)
        student_profile = create_student(uid, {
            "uid": uid,
            "name": name,
            "email": email,
            "course": course,
            "courseId": course_id,
            "semester": int(semester),
            "facultyAssigned": faculty_assigned,
            "feesPaid": False
        })

        return jsonify({
            "message": "Student created successfully",
            "uid": uid,
            "email": email,
            "password": password,
            "isAutoGenerated": is_auto_generated
        }), 201

    except Exception as e:
        print(f"FAILED TO CREATE STUDENT: {str(e)}")
        return jsonify({"error": f"Failed to create student: {str(e)}"}), 500

@admin_bp.route("/update-student", methods=["PUT"])
@verify_token
@require_role("admin")
def edit_student():
    data = request.json
    uid = data.get("uid")
    if not uid: return jsonify({"error": "uid is required"}), 400
    
    try:
        # 1. Update Firebase Auth if email/name/password changed
        auth_updates = {}
        if data.get("email"): auth_updates["email"] = data["email"]
        if data.get("name"): auth_updates["display_name"] = data["name"]
        if data.get("password"): auth_updates["password"] = data["password"]
        
        if auth_updates:
            firebase_auth.update_user(uid, **auth_updates)
            
        # 2. Update Firestore (users collection)
        user_updates = {
            "name": data.get("name"),
            "email": data.get("email"),
            "courseId": data.get("courseId"),
            "semester": int(data.get("semester")) if data.get("semester") else None,
            "role": "student"
        }
        user_updates = {k: v for k, v in user_updates.items() if v is not None}
        create_user(uid, user_updates)
        
        # 3. Update Firestore (students collection)
        student_updates = {
            "name": data.get("name"),
            "email": data.get("email"),
            "course": data.get("course"),
            "courseId": data.get("courseId"),
            "semester": int(data.get("semester")) if data.get("semester") else None,
            "facultyAssigned": data.get("facultyAssigned"),
            "totalFees": float(data.get("totalFees")) if data.get("totalFees") is not None else None,
            "pendingAmount": float(data.get("pendingAmount")) if data.get("pendingAmount") is not None else None
        }
        student_updates = {k: v for k, v in student_updates.items() if v is not None}
        update_student(uid, student_updates)
        
        return jsonify({"message": "Student profile synchronized successfully"}), 200
    except Exception as e:
        return jsonify({"error": str(e)}), 500

