@admin_bp.route("/seed/marks", methods=["POST"])
@verify_token
@require_role("admin")
def seed_marks():
    students = list_students()
    faculty = list_users_by_role("faculty")
    
    if not students or not faculty:
        return jsonify({"error": "No students or faculty found to seed marks for."}), 400

    faculty_ids = [f["uid"] for f in faculty]
    faculty_names = [f["name"] for f in faculty]

    subjects = ["Mathematics", "Computer Science", "Physics", "English", "Chemistry"]
    exam_types = ["Midterm", "Final", "Assignment 1", "Assignment 2", "Project"]
    
    marks_added = 0
    errors = 0

    for student in students:
        sid = student.get("uid") or student.get("id")
        if not sid: continue
        
        # Pick 3-5 random subjects to avoid too many entries
        student_subjects = random.sample(subjects, random.randint(3, 5))
        
        for subject in student_subjects:
            for exam_type in exam_types:
                # 80% chance they took this exam type to add realism
                if random.random() < 0.8:
                    teacher_idx = random.randint(0, len(faculty)-1)
                    teacher_uid = faculty_ids[teacher_idx]
                    teacher_name = faculty_names[teacher_idx]
                    
                    date_str = (datetime.now() - timedelta(days=random.randint(1, 60))).strftime("%Y-%m-%d")
                    
                    # Score between 50 and 95
                    score = random.randint(50, 95)
                    max_marks = 100 if exam_type in ["Midterm", "Final"] else random.choice([20, 50, 100])
                    if max_marks < 100:
                        score = int((score / 100) * max_marks)
                    
                    try:
                        add_mark(sid, {
                            "subject": subject,
                            "examType": exam_type,
                            "score": float(score),
                            "maxMarks": float(max_marks),
                            "date": date_str,
                            "markedBy": teacher_uid,
                            "teacherName": teacher_name,
                            "createdAt": datetime.now().isoformat(),
                            "lastUpdatedAt": datetime.now().isoformat()
                        })
                        marks_added += 1
                    except Exception as e:
                        # Ignore duplicates or validation errors from add_mark
                        errors += 1

    return jsonify({
        "message": "Marks seeded successfully.",
        "records_added": marks_added,
        "errors_skipped": errors
    }), 200
